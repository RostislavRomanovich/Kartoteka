-- Этап 22. Расширенные сведения сотрудников и планирование отпусков.
-- Выполнять на резервной копии БД, от имени владельца схемы, после проверки текущих таблиц.
BEGIN;

CREATE TABLE IF NOT EXISTS "EmployeeExtendedData" (
    "EmployeeId" bigint PRIMARY KEY REFERENCES "Employees"("Id") ON DELETE CASCADE,
    "Inn" varchar(12), "Snils" varchar(14), "PekNumber" varchar(100),
    "DactyloscopyPerformed" boolean, "DactyloscopyDate" date,
    "BloodGroup" varchar(12), "RhFactor" varchar(8),
    "DnaTestPerformed" boolean, "DnaTestDate" date,
    "UmoPassedOn" date, "UmoExpiresOn" date,
    "FitnessCategory" varchar(100), "HeightCm" numeric(5,2), "WeightKg" numeric(5,2),
    "ClothingSize" varchar(40), "ShoeSize" varchar(20),
    "DrivingLicenseSeries" varchar(30), "DrivingLicenseNumber" varchar(30),
    "DrivingLicenseIssuedBy" varchar(300), "DrivingLicenseIssuedOn" date,
    "UpdatedUtc" timestamp with time zone NOT NULL DEFAULT now(), "UpdatedByUserId" varchar(450),
    CONSTRAINT "CK_ExtendedData_Height" CHECK ("HeightCm" IS NULL OR ("HeightCm" >= 30 AND "HeightCm" <= 260)),
    CONSTRAINT "CK_ExtendedData_Weight" CHECK ("WeightKg" IS NULL OR ("WeightKg" >= 1 AND "WeightKg" <= 500)),
    CONSTRAINT "CK_ExtendedData_UmoDates" CHECK ("UmoExpiresOn" IS NULL OR "UmoPassedOn" IS NULL OR "UmoExpiresOn" >= "UmoPassedOn")
);

CREATE TABLE IF NOT EXISTS "EmployeeConfidentialHealthRecords" (
    "EmployeeId" bigint PRIMARY KEY REFERENCES "Employees"("Id") ON DELETE CASCADE,
    "PsychiatricFitnessCategory" varchar(100), "PsychiatricAssessmentDate" date,
    "RestrictedNote" varchar(1000), "UpdatedUtc" timestamp with time zone NOT NULL DEFAULT now(),
    "UpdatedByUserId" varchar(450)
);

CREATE TABLE IF NOT EXISTS "EmployeeLeaveRecords" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeId" bigint NOT NULL REFERENCES "Employees"("Id") ON DELETE CASCADE,
    "LeaveType" varchar(20) NOT NULL DEFAULT 'main', "PlannedStart" date NOT NULL, "PlannedEnd" date NOT NULL,
    "PlannedDays" integer NOT NULL, "ActualStart" date, "ActualEnd" date, "ActualDays" integer,
    "Status" varchar(20) NOT NULL DEFAULT 'planned', "Note" varchar(1000),
    "CreatedUtc" timestamp with time zone NOT NULL DEFAULT now(), "UpdatedUtc" timestamp with time zone NOT NULL DEFAULT now(),
    "UpdatedByUserId" varchar(450),
    CONSTRAINT "CK_LeaveRecord_Type" CHECK ("LeaveType" IN ('main','veteran','additional','other')),
    CONSTRAINT "CK_LeaveRecord_Status" CHECK ("Status" IN ('planned','in-progress','completed','cancelled')),
    CONSTRAINT "CK_LeaveRecord_PlannedRange" CHECK ("PlannedEnd" >= "PlannedStart"),
    CONSTRAINT "CK_LeaveRecord_ActualRange" CHECK ("ActualEnd" IS NULL OR "ActualStart" IS NULL OR "ActualEnd" >= "ActualStart"),
    CONSTRAINT "CK_LeaveRecord_Days" CHECK ("PlannedDays" > 0 AND ("ActualDays" IS NULL OR "ActualDays" >= 0))
);
CREATE INDEX IF NOT EXISTS "IX_EmployeeLeaveRecords_EmployeeId_PlannedStart_PlannedEnd" ON "EmployeeLeaveRecords" ("EmployeeId", "PlannedStart", "PlannedEnd");

CREATE TABLE IF NOT EXISTS "EmployeeLeaveEntitlements" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeId" bigint NOT NULL REFERENCES "Employees"("Id") ON DELETE CASCADE,
    "CalendarYear" integer NOT NULL, "MainDays" integer NOT NULL DEFAULT 0, "VeteranDays" integer NOT NULL DEFAULT 0,
    "AdditionalDays" integer NOT NULL DEFAULT 0, "CarryoverDays" integer NOT NULL DEFAULT 0, "ManualAdjustmentDays" integer NOT NULL DEFAULT 0,
    "BasisNote" varchar(1000), "UpdatedUtc" timestamp with time zone NOT NULL DEFAULT now(), "UpdatedByUserId" varchar(450),
    CONSTRAINT "CK_LeaveEntitlement_NonNegative" CHECK ("MainDays" >= 0 AND "VeteranDays" >= 0 AND "AdditionalDays" >= 0 AND "CarryoverDays" >= 0),
    CONSTRAINT "AK_EmployeeLeaveEntitlements_EmployeeId_CalendarYear" UNIQUE ("EmployeeId", "CalendarYear")
);

CREATE TABLE IF NOT EXISTS "EmployeeLeavePreferences" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeId" bigint NOT NULL REFERENCES "Employees"("Id") ON DELETE CASCADE,
    "CalendarYear" integer NOT NULL, "Month" integer NOT NULL, "Priority" integer NOT NULL, "Note" varchar(500),
    CONSTRAINT "CK_LeavePreference_Month" CHECK ("Month" BETWEEN 1 AND 12),
    CONSTRAINT "CK_LeavePreference_Priority" CHECK ("Priority" BETWEEN 1 AND 12),
    CONSTRAINT "AK_EmployeeLeavePreferences_EmployeeId_CalendarYear_Month" UNIQUE ("EmployeeId", "CalendarYear", "Month")
);

CREATE TABLE IF NOT EXISTS "LeaveBlackoutPeriods" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StartDate" date NOT NULL, "EndDate" date NOT NULL,
    "OrganizationalUnitId" bigint REFERENCES "OrganizationalUnits"("Id") ON DELETE SET NULL,
    "Reason" varchar(300) NOT NULL, "IsActive" boolean NOT NULL DEFAULT true,
    "CreatedUtc" timestamp with time zone NOT NULL DEFAULT now(), "CreatedByUserId" varchar(450),
    CONSTRAINT "CK_LeaveBlackout_DateRange" CHECK ("EndDate" >= "StartDate")
);

COMMIT;
